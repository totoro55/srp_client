function fold(value: string): string {
    return value.toLocaleLowerCase("ru").replaceAll("ё", "е");
}

export function visibleHelp(anchors: boolean): HelpSection[] {
    return HELP_SECTIONS.flatMap((section) => {
        const items = section.items.filter((item) => item.wiki !== true || anchors);
        return items.length > 0 ? [{ ...section, items }] : [];
    });
}

export function filterHelp(sections: HelpSection[], query: string): HelpSection[] {
    const needle = fold(query.trim());
    if (!needle) {
        return sections;
    }
    return sections.flatMap((section) => {
        if (fold(section.title).includes(needle)) {
            return [section];
        }
        const items = section.items.filter((item) => fold(item.title).includes(needle) || fold(helpPlain(item.body)).includes(needle));
        return items.length > 0 ? [{ ...section, items }] : [];
    });
}
