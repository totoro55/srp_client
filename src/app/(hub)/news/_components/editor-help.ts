export type HelpCommand = { command: string };
export type HelpKeys = { keys: string[] };
export type HelpPart = string | HelpCommand | HelpKeys;

export type HelpOption = {
    command?: string;
    /** Значок «—» в палитре границы ячейки. В остальных меню у «Без обводки» другой знак. */
    mark?: "dash";
    parts: HelpPart[];
};

export type HelpBlock =
    | { kind: "text"; parts: HelpPart[] }
    | { kind: "options"; items: HelpOption[] };

export type HelpItem = {
    title: string;
    body: HelpBlock[];
    wiki?: boolean;
};

export type HelpSection = {
    id: string;
    title: string;
    items: HelpItem[];
};

function cmd(command: string): HelpCommand {
    return { command };
}

function keys(...names: string[]): HelpKeys {
    return { keys: names };
}

function text(...parts: HelpPart[]): HelpBlock {
    return { kind: "text", parts };
}

function options(...items: HelpOption[]): HelpBlock {
    return { kind: "options", items };
}

function option(command: string, ...parts: HelpPart[]): HelpOption {
    return { command, parts };
}

function plainParts(parts: HelpPart[]): string {
    return parts.map((part) => {
        if (typeof part === "string") {
            return part;
        }
        return "command" in part ? part.command : part.keys.join("+");
    }).join("");
}

export function helpPlain(blocks: HelpBlock[]): string {
    return blocks.map((block) => {
        if (block.kind === "text") {
            return plainParts(block.parts);
        }
        return block.items.map((item) => `${item.command ?? ""} ${plainParts(item.parts)}`).join(" ");
    }).join(" ");
}

