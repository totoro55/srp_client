export function tableIntro(name: string, sqlNote: string, schema: string): string {
    const text = sqlNote.trim() || INTRO[name] || "Таблица приложения.";
    return schema === "public" ? text : `${text} Лежит в схеме ${schema}.`;
}

export function fieldSense(table: string, column: string, sqlNote: string): string {
    const fromSql = sqlNote.replaceAll(/\s+/g, " ").trim();
    if (fromSql) {
        return fromSql;
    }
    return NOTES[`${table}.${column}`] ?? SHARED[column] ?? "";
}
