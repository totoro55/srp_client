-- Режим бригады действует с месяца записи до следующей записи филиала.
-- Повторный запуск только обновляет пояснение.

COMMENT ON TABLE main.branch_brigades IS
    'Режим бригады филиала с месяца period до следующей записи этого филиала: выключена, общая или отдельные группы.';

COMMENT ON COLUMN main.branch_brigades.period IS
    'Месяц, с которого действует режим. Следующие месяцы наследуют его, пока нет более поздней строки.';
